def count_all():
    # 人物逐回
    pm = {p["name"]: [0]*121 for p in PERSONS}
    place_names = [n for v in PLACES.values() for n in v]
    plm = {n: [0]*121 for n in place_names}
    artm = {a[0]: [0]*121 for a in ARTIFACTS}
    for c in chap:
        no = c["no"]
        body = "\n".join(c["paras"])
        # 人物：用别名集合匹配
        for alias, name in ALIAS.items():
            cnt = body.count(alias)
            if cnt:
                pm[name][no] += cnt
        for ch, (name, pat) in SINGLE.items():
            cnt = len(re.findall(pat, body))
            if cnt:
                pm[name][no] += cnt
        for n in place_names:
            cnt = body.count(n)
            if cnt:
                plm[n][no] += cnt
        for a in ARTIFACTS:
            cnt = body.count(a[0])
            if cnt:
                artm[a[0]][no] += cnt
    return pm, plm, artm

