# ---------- 人物提及統計 ----------
person_count = collections.Counter()
person_first = {}
person_spark = collections.defaultdict(list)  # name -> [(chapter,count)]
person_max = collections.Counter()
# 匹配優先：長名優先（避免"曹操"匹配到"曹"、"劉"等）
names_sorted = sorted(set(list(alias_map.keys())), key=lambda x:-len(x))
for lid, cno, ctitle, pi, text in lines:
    counted_in_para = set()
    for a in names_sorted:
        if a in text:
            canon = alias_map[a]
            # 記錄提及（每段每人物最多一次以避免別名疊加）
            if canon not in counted_in_para:
                person_count[canon] += text.count(a)  # 允許同段多次
                counted_in_para.add(canon)
                if canon not in person_first:
                    person_first[canon] = cno
    # 每回小計
for lid, cno, ctitle, pi, text in lines:
    for a in names_sorted:
        if a in text:
            canon = alias_map[a]
            c = text.count(a)
            person_spark[canon].append((cno,c))
            break
# 匯總 spark
person_spark_sum = {}
for n, lst in person_spark.items():
    d = collections.Counter()
    for cn,c in lst: d[cn]+=c
    person_spark_sum[n] = sorted(d.items())
    person_max[n] = max(d.values())

# 更新 p_db -> persons
persons_out = []
for p in p_db:
    n = p["name"]
    po = dict(p)
    po["total"] = person_count.get(n,0)
    po["spark"] = person_spark_sum.get(n,[])
    po["max"] = person_max.get(n,0)
    # first: 若手動設置且不為0，保留；否則用自動檢測
    if not po.get("first"): po["first"] = person_first.get(n,0)
    persons_out.append(po)
# 按提及排序
